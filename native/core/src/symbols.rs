#[cfg(test)]
mod tests {
    use super::SYMBOLS;
    use crate::projects::PROJECT_ICONS;

    #[test]
    fn matches_the_typescript_list_name_for_name() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../src/shared/symbols.ts");
        let ts = std::fs::read_to_string(path).unwrap();
        let body = ts.split("SYMBOLS: readonly string[] = [").nth(1).unwrap();
        let body = body.split("];").next().unwrap();
        let mut names: Vec<&str> = PROJECT_ICONS.to_vec();
        names.extend(body.split('"').skip(1).step_by(2));
        assert_eq!(SYMBOLS.to_vec(), names);
    }
}
